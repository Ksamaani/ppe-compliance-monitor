"""Dataset acquisition and YOLO `data.yaml` authoring.

Shared by the local smoke test, the Colab training notebook and the evaluation
notebook, so all three see exactly the same splits and the same class order.
Getting the class order wrong is a silent failure: training would succeed and
every metric would be attributed to the wrong label.

The dataset is Roboflow's Construction Site Safety project, mirrored on Kaggle.
kagglehub downloads it anonymously - no API key, no account.
"""

from __future__ import annotations

import random
import shutil
from collections import Counter
from pathlib import Path

KAGGLE_ID = "snehilsanyal/construction-site-safety-image-dataset-roboflow"

# Must match the dataset's own class order, and ppe_monitor.config.CLASS_NAMES.
CLASS_NAMES: list[str] = [
    "Hardhat",
    "Mask",
    "NO-Hardhat",
    "NO-Mask",
    "NO-Safety Vest",
    "Person",
    "Safety Cone",
    "Safety Vest",
    "machinery",
    "vehicle",
]

SPLIT_ALIASES = {
    "train": ("train", "training"),
    "valid": ("valid", "val", "validation"),
    "test": ("test", "testing"),
}


def download() -> Path:
    """Download the dataset via kagglehub and return its extracted root."""
    import kagglehub

    path = Path(kagglehub.dataset_download(KAGGLE_ID))
    print(f"dataset root: {path}")
    return path


def find_split_root(root: Path) -> Path:
    """Locate the directory that actually holds train/valid/test.

    The Kaggle archive nests the YOLO layout a level or two down, and the exact
    depth has changed between versions, so search rather than hardcode.
    """
    candidates = [root, *[p for p in root.rglob("*") if p.is_dir()]]
    for candidate in candidates:
        names = {p.name.lower() for p in candidate.iterdir() if p.is_dir()}
        if any(alias in names for alias in SPLIT_ALIASES["train"]) and any(
            alias in names for alias in SPLIT_ALIASES["valid"]
        ):
            return candidate
    raise FileNotFoundError(f"No train/valid split directories found under {root}")


def resolve_splits(split_root: Path) -> dict[str, Path]:
    """Map canonical split names to their directories."""
    present = {p.name.lower(): p for p in split_root.iterdir() if p.is_dir()}
    out: dict[str, Path] = {}
    for canonical, aliases in SPLIT_ALIASES.items():
        for alias in aliases:
            if alias in present:
                out[canonical] = present[alias]
                break
    return out


def describe(splits: dict[str, Path]) -> dict[str, dict[str, int]]:
    """Count images and labelled instances per split, and instances per class."""
    report: dict[str, dict[str, int]] = {}
    for name, path in splits.items():
        images = list((path / "images").glob("*.*")) if (path / "images").exists() else []
        labels = list((path / "labels").glob("*.txt")) if (path / "labels").exists() else []
        counter: Counter[int] = Counter()
        for label in labels:
            for line in label.read_text(encoding="utf-8", errors="ignore").splitlines():
                parts = line.split()
                if parts:
                    counter[int(parts[0])] += 1
        report[name] = {
            "images": len(images),
            "label_files": len(labels),
            "instances": sum(counter.values()),
            "per_class": {CLASS_NAMES[k]: v for k, v in sorted(counter.items()) if k < len(CLASS_NAMES)},
        }
    return report


def write_data_yaml(split_root: Path, dest: Path, splits: dict[str, Path] | None = None) -> Path:
    """Write a YOLO data.yaml pointing at absolute split paths.

    Absolute paths sidestep Ultralytics' datasets_dir resolution, which is a
    global setting and a common source of "dataset not found" in Colab.
    """
    splits = splits or resolve_splits(split_root)
    lines = [
        "# Auto-generated by ppe_monitor.dataset.write_data_yaml",
        f"# Source: https://www.kaggle.com/datasets/{KAGGLE_ID}",
        f"path: {split_root.as_posix()}",
    ]
    for canonical in ("train", "valid", "test"):
        if canonical in splits:
            key = "val" if canonical == "valid" else canonical
            lines.append(f"{key}: {(splits[canonical] / 'images').as_posix()}")
    lines.append(f"nc: {len(CLASS_NAMES)}")
    lines.append("names:")
    lines.extend(f"  {i}: {name}" for i, name in enumerate(CLASS_NAMES))

    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return dest


def make_subset(
    splits: dict[str, Path],
    dest: Path,
    n_train: int = 24,
    n_valid: int = 12,
    seed: int = 42,
) -> Path:
    """Build a tiny copy of the dataset for smoke testing on CPU.

    Not for producing a usable model - only for proving every API call in the
    training pipeline works before committing a GPU run to it.
    """
    rng = random.Random(seed)
    if dest.exists():
        shutil.rmtree(dest)

    picked: dict[str, Path] = {}
    for canonical, n in (("train", n_train), ("valid", n_valid)):
        src = splits[canonical]
        images = sorted((src / "images").glob("*.*"))
        chosen = rng.sample(images, min(n, len(images)))
        img_dir = dest / canonical / "images"
        lbl_dir = dest / canonical / "labels"
        img_dir.mkdir(parents=True, exist_ok=True)
        lbl_dir.mkdir(parents=True, exist_ok=True)
        for image in chosen:
            shutil.copy2(image, img_dir / image.name)
            label = src / "labels" / f"{image.stem}.txt"
            if label.exists():
                shutil.copy2(label, lbl_dir / label.name)
        picked[canonical] = dest / canonical

    return write_data_yaml(dest, dest / "data.yaml", picked)
